/**
 * Token pipeline: src/lib/tokens/*.tokens.json (DTCG) → tokens.css, tokens.scss, tokens.ts.
 *
 * Run with `pnpm tokens`. The outputs are committed (consumers install the package from a
 * pinned git SHA without a build step); CI fails when they are out of date.
 *
 * Naming: the CSS custom property is `--cui-` plus the token path joined with `-`. Semantic
 * colours drop their leading `color` group, so `color.text.default` is `--cui-text-default`
 * and `palette.ink` is `--cui-palette-ink`.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import StyleDictionary from 'style-dictionary';
import { formattedVariables } from 'style-dictionary/utils';

const DIR = fileURLToPath(new URL('../src/lib/tokens/', import.meta.url));
const THEMES = /** @type {const} */ (['light', 'dark']);
// Output order; color.<theme>.tokens.json is added per theme.
const FILES = [
	'palette',
	'typography',
	'space',
	'radius',
	'border',
	'shadow',
	'motion',
	'layout'
].map((name) => `${name}.tokens.json`);

const HEADER = [
	'Generated by scripts/build-tokens.js from src/lib/tokens/*.tokens.json.',
	'Do not edit by hand: change the JSON source and run `pnpm tokens`.'
];

/** @param {{ value: number, unit: string }} v */
const isUnitValue = (v) =>
	typeof v === 'object' && v !== null && 'value' in v && 'unit' in v && !Array.isArray(v);

/** @param {unknown} v @returns {unknown} */
function flattenUnits(v) {
	if (isUnitValue(v)) return `${v.value}${v.unit}`;
	if (Array.isArray(v) || typeof v !== 'object' || v === null) return v;
	return Object.fromEntries(Object.entries(v).map(([k, sub]) => [k, flattenUnits(sub)]));
}

StyleDictionary.registerTransform({
	name: 'name/cui',
	type: 'name',
	transform: (token, options) => {
		const path = token.path[0] === 'color' ? token.path.slice(1) : token.path;
		// Expanded typography sub-values arrive as fontSize, letterSpacing, …
		const kebab = path.map((p) => p.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`));
		return [options.prefix, ...kebab].filter(Boolean).join('-');
	}
});

// DTCG 2025.10 writes dimensions and durations as { value, unit }; CSS wants "16px".
// Composite values (shadow, typography) carry such objects inside, so flatten those too.
StyleDictionary.registerTransform({
	name: 'value/units',
	type: 'value',
	transitive: true,
	filter: (token) => typeof token.$value === 'object' && token.$value !== null,
	transform: (token) => flattenUnits(token.$value)
});

// Keep colours as written (hex, hex with alpha for the fixed alpha neutrals), only lower-cased.
StyleDictionary.registerTransform({
	name: 'color/hex-lower',
	type: 'value',
	transitive: true,
	filter: (token) => token.$type === 'color' && typeof token.$value === 'string',
	transform: (token) => token.$value.toLowerCase()
});

const TRANSFORMS = [
	'name/cui',
	'value/units',
	'color/hex-lower',
	'fontFamily/css',
	'cubicBezier/css',
	'shadow/css/shorthand'
];

const isColorRole = (/** @type {{ path: string[] }} */ token) => token.path[0] === 'color';

/**
 * Resolved tokens for one theme: every non-colour file plus that theme's colour roles.
 * Files are merged here rather than by Style Dictionary, which reports each file's top-level
 * $description as a collision; real collisions (one top-level group in two files) still fail.
 */
async function loadTheme(/** @type {(typeof THEMES)[number]} */ theme) {
	const files = [...FILES, `color.${theme}.tokens.json`];
	const unknown = (await readdir(DIR)).filter(
		(f) => f.endsWith('.tokens.json') && !f.startsWith('color.') && !FILES.includes(f)
	);
	if (unknown.length) throw new Error(`tokens: add ${unknown.join(', ')} to FILES`);
	/** @type {Record<string, unknown>} */
	const tokens = {};
	for (const file of files) {
		const { $description, ...groups } = JSON.parse(await readFile(DIR + file, 'utf8'));
		for (const [key, group] of Object.entries(groups)) {
			if (key in tokens) throw new Error(`tokens: group "${key}" is defined twice (${file})`);
			tokens[key] = group;
		}
	}
	const sd = new StyleDictionary({
		tokens,
		usesDtcg: true,
		// One custom property per typography sub-value (font shorthand cannot carry letter-spacing).
		expand: { include: ['typography'] },
		log: { verbosity: 'verbose', warnings: 'error' },
		platforms: {
			css: { prefix: 'cui', transforms: TRANSFORMS }
		}
	});
	return sd.getPlatformTokens('css');
}

/**
 * @param {import('style-dictionary').Dictionary} dictionary
 * @param {(token: import('style-dictionary').TransformedToken) => boolean} filter
 */
function cssBlock(dictionary, filter) {
	return formattedVariables({
		format: 'css',
		dictionary: { ...dictionary, allTokens: dictionary.allTokens.filter(filter) },
		// Colour roles stay linked to the palette (var(--cui-palette-ink)); everything else is
		// written as its resolved value.
		outputReferences: (token) => token.$type === 'color',
		usesDtcg: true,
		formatting: { indentation: '\t\t' }
	});
}

function css(/** @type {Record<string, import('style-dictionary').Dictionary>} */ dict) {
	const comment = (/** @type {string[]} */ lines) =>
		['/*', ...lines.map((l) => (l ? ` * ${l}` : ' *')), ' */'].join('\n');
	return `${comment([
		...HEADER,
		'',
		'Palette tokens (--cui-palette-*) hold the fixed palette. Semantic colour roles point at',
		'exactly one palette value and switch with data-theme (light is the default; dark works on',
		'the whole page or on a subtree such as a header). Components use semantic tokens only.'
	])}

@layer calliope.tokens {
	:root {
${cssBlock(dict.light, (t) => !isColorRole(t))}
	}

	:root,
	[data-theme='light'] {
		color-scheme: light;
${cssBlock(dict.light, isColorRole)}
	}

	[data-theme='dark'] {
		color-scheme: dark;
${cssBlock(dict.dark, isColorRole)}
	}
}
`;
}

/** Sass variables with resolved values (light theme). Theme-aware colours come from tokens.css. */
function scss(/** @type {Record<string, import('style-dictionary').Dictionary>} */ dict) {
	const vars = formattedVariables({
		format: 'sass',
		dictionary: dict.light,
		outputReferences: false,
		usesDtcg: true
	});
	return `// ${HEADER.join('\n// ')}
//
// Static values, light theme. For colours that follow data-theme, use the custom properties
// from tokens.css (var(--cui-text-default)); use these where Sass needs a value, e.g. in
// media queries ($cui-breakpoint-lg).

${vars}
`;
}

function ts(/** @type {Record<string, import('style-dictionary').Dictionary>} */ dict) {
	const strip = (/** @type {string} */ name) => name.replace(/^cui-/, '');
	/** @param {import('style-dictionary').TransformedToken[]} list */
	const record = (list) => Object.fromEntries(list.map((t) => [strip(t.name), t.$value]));
	const json = (/** @type {unknown} */ v) => JSON.stringify(v, null, '\t');

	const palette = dict.light.allTokens
		.filter((t) => t.path[0] === 'palette')
		.map((t) => ({
			name: t.path[1],
			hex: t.original.$value,
			group: t.$extensions?.calliope?.group
		}));
	const shared = record(dict.light.allTokens.filter((t) => !isColorRole(t)));
	const colors = {
		light: record(dict.light.allTokens.filter(isColorRole)),
		dark: record(dict.dark.allTokens.filter(isColorRole))
	};

	return `// ${HEADER.join('\n// ')}

export type PaletteGroup = 'neutral' | 'brand' | 'color' | 'error';

export interface PaletteColor {
	/** Token name, also the CSS custom property \`--cui-palette-<name>\`. */
	name: string;
	hex: string;
	group: PaletteGroup;
}

/** The fixed Calliope palette. No derived scales: every colour in the library is one of these. */
export const palette = ${json(palette)} as const satisfies readonly PaletteColor[];

export type PaletteName = (typeof palette)[number]['name'];

/** Theme-independent tokens, keyed by CSS custom property without \`--cui-\`. */
export const tokens = ${json(shared)} as const;

/** Semantic colour roles per theme, keyed by CSS custom property without \`--cui-\`. */
export const colors = ${json(colors)} as const;

export type TokenName = keyof typeof tokens;
export type ColorRole = keyof (typeof colors)['light'];
export type Theme = keyof typeof colors;

/** \`var(--cui-<name>)\` for a token or colour role. */
export const cssVar = (name: TokenName | ColorRole): string => \`var(--cui-\${name})\`;
`;
}

const dict = Object.fromEntries(
	await Promise.all(THEMES.map(async (theme) => [theme, await loadTheme(theme)]))
);

/** Written through Prettier so the outputs pass `pnpm lint` as they are. */
async function write(/** @type {string} */ file, /** @type {string} */ source) {
	const path = DIR + file;
	const options = await prettier.resolveConfig(path);
	await writeFile(path, await prettier.format(source, { ...options, filepath: path }));
}

await Promise.all([
	write('tokens.css', css(dict)),
	write('tokens.scss', scss(dict)),
	write('tokens.ts', ts(dict))
]);

console.log('tokens: wrote tokens.css, tokens.scss, tokens.ts');
